# One-shot setup for Tailputer Zero's Tailscale integration. Run once over
# SSH on the CardputerZero *before* installing the app's .deb. Idempotent --
# safe to re-run if something changes later (new app user, Tailscale
# reinstalled, etc).
#
# What it does, in order:
#   1. Installs Tailscale if it isn't already (official install script).
#   2. Runs `tailscale up` if the daemon isn't already connected.
#   3. Installs scripts/cardputerzero-tailscale-helper.sh to
#      /usr/local/bin/cardputerzero-tailscale-helper.
#   4. Generates and installs a sudoers drop-in granting NOPASSWD on that
#      exact helper script only (never on the real `tailscale` binary, never
#      with a wildcard argument) for the app user.
#
# Usage: sudo ./setup-tailputer-zero.sh [app-user]
#   app-user defaults to whoever invoked sudo (i.e. your own login), which
#   is almost always right -- the CardputerZero App Store runs installed
#   apps as the logged-in user, not a dedicated service account. Pass it
#   explicitly only if the app will run as someone else.

set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
HELPER_SRC="${SCRIPT_DIR}/cardputerzero-tailscale-helper.sh"
HELPER_DST="/usr/local/bin/cardputerzero-tailscale-helper"
SUDOERS_DST="/etc/sudoers.d/99-cardputerzero-tailscale"

if [ "$(id -u)" -ne 0 ]; then
    echo "Run this with sudo: sudo $0 [app-user]" >&2
    exit 1
fi

APP_USER="${1:-${SUDO_USER:-}}"
if [ -z "${APP_USER}" ]; then
    APP_USER="$(logname 2>/dev/null || true)"
fi
if [ -z "${APP_USER}" ]; then
    echo "Could not determine the app user automatically (not run via sudo" >&2
    echo "from a login shell). Pass it explicitly: sudo $0 <app-user>" >&2
    exit 1
fi
if ! id "${APP_USER}" >/dev/null 2>&1; then
    echo "User '${APP_USER}' does not exist on this device." >&2
    exit 1
fi

echo "==> Setting up Tailputer Zero's Tailscale access for user: ${APP_USER}"

# 1. Install Tailscale if missing.
if command -v tailscale >/dev/null 2>&1; then
    echo "==> Tailscale already installed ($(tailscale version | head -n1))"
else
    echo "==> Installing Tailscale..."
    curl -fsSL https://tailscale.com/install.sh | sh
fi

# 2. Bring it up if the daemon isn't already connected. `tailscale status`
# exits non-zero (and prints a message like "Tailscale is stopped" or
# "Logged out") when it isn't, rather than printing a peer table.
if tailscale status >/dev/null 2>&1; then
    echo "==> Tailscale already up"
else
    echo "==> Running 'tailscale up' -- complete the interactive login if prompted"
    tailscale up
fi

# 3. Install the helper script.
if [ ! -f "${HELPER_SRC}" ]; then
    echo "Helper script not found at ${HELPER_SRC} (run this from the repo's scripts/ directory)" >&2
    exit 1
fi
install -m 0755 "${HELPER_SRC}" "${HELPER_DST}"
echo "==> Installed helper script: ${HELPER_DST}"

# 4. Generate and install the sudoers drop-in. Written to a temp file and
# validated with visudo *before* it ever touches /etc/sudoers.d -- a bad
# sudoers file there can lock out sudo entirely.
TMP_SUDOERS="$(mktemp)"
trap 'rm -f "${TMP_SUDOERS}"' EXIT

cat > "${TMP_SUDOERS}" <<EOF
# Generated by scripts/setup-tailputer-zero.sh -- re-run that script to
# regenerate rather than hand-editing this file.
#
# Grants NOPASSWD only on the exact fixed-verb helper script, never on the
# real tailscale binary or any wildcard argument form. Tailputer Zero never
# runs as root itself; it only invokes this one pre-authorized script.
${APP_USER} ALL=(root) NOPASSWD: ${HELPER_DST} status
${APP_USER} ALL=(root) NOPASSWD: ${HELPER_DST} up
${APP_USER} ALL=(root) NOPASSWD: ${HELPER_DST} up-with-key *
${APP_USER} ALL=(root) NOPASSWD: ${HELPER_DST} down
EOF

visudo -c -f "${TMP_SUDOERS}"
install -m 0440 -o root -g root "${TMP_SUDOERS}" "${SUDOERS_DST}"
echo "==> Installed sudoers rule: ${SUDOERS_DST}"

echo "==> Done. Install Tailputer Zero's .deb now -- Connect/Disconnect will work immediately for '${APP_USER}'."
